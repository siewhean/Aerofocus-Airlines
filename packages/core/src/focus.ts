import { MINUTE, type Instant } from "./time";

/** Break settings (FR-033). Provisional defaults. */
export interface BreakSchedule {
  /** auto: breaks start and end on schedule; manual: the user starts and ends each break. */
  mode: "auto" | "manual";
  focusMinutes: number;
  breakMinutes: number;
  /** Every Nth break is a long rest. 0 disables long rests. */
  longBreakEvery: number;
  longBreakMinutes: number;
}

export const DEFAULT_BREAK_SCHEDULE: BreakSchedule = {
  mode: "auto",
  focusMinutes: 50,
  breakMinutes: 10,
  longBreakEvery: 3,
  longBreakMinutes: 30,
};

export function validateBreakSchedule(s: BreakSchedule): string[] {
  const errors: string[] = [];
  if (s.mode !== "auto" && s.mode !== "manual") errors.push("mode must be auto or manual");
  if (!(s.focusMinutes >= 5 && s.focusMinutes <= 240)) errors.push("focusMinutes must be 5–240");
  if (!(s.breakMinutes >= 1 && s.breakMinutes <= 60)) errors.push("breakMinutes must be 1–60");
  if (!(Number.isInteger(s.longBreakEvery) && s.longBreakEvery >= 0)) errors.push("longBreakEvery must be ≥ 0");
  if (!(s.longBreakMinutes >= 1 && s.longBreakMinutes <= 120)) errors.push("longBreakMinutes must be 1–120");
  return errors;
}

/**
 * User actions on the focus timeline.
 * - break_start: start a break now (manual)
 * - break_end: end a manual break; focus resumes immediately
 * - back: confirms "I'm back" after an automatic break (FR-040), or ends any break early
 */
export type FocusEventType = "break_start" | "break_end" | "back";

export interface FocusEvent {
  type: FocusEventType;
  at: Instant;
}

/**
 * focus: credited study time. break: a break. awaiting_return: an automatic break has ended and the
 * user has not yet confirmed they are back; this time is neither focus nor break.
 */
export type SegmentKind = "focus" | "break" | "awaiting_return";

export interface Segment {
  kind: SegmentKind;
  start: Instant;
  end: Instant;
  /** True for breaks generated by the automatic schedule. */
  auto?: boolean;
}

export interface DeriveSegmentsInput {
  /** When focus begins: pushback, or boarding time for late Community Flight passengers (FR-013a). */
  focusStart: Instant;
  until: Instant;
  schedule: BreakSchedule;
  events: readonly FocusEvent[];
}

function breakLengthMs(schedule: BreakSchedule, breakNumber: number): number {
  const isLong = schedule.longBreakEvery > 0 && breakNumber % schedule.longBreakEvery === 0;
  return (isLong ? schedule.longBreakMinutes : schedule.breakMinutes) * MINUTE;
}

/**
 * Replays the focus timeline from stored events and the break schedule. Automatic breaks are
 * computed, not stored, so state never depends on a running timer (NFR-001).
 */
export interface FocusTimeline {
  segments: Segment[];
  /** State at `until`, including a state entered exactly at `until`. */
  current: SegmentKind;
}

export function deriveSegments(input: DeriveSegmentsInput): Segment[] {
  return deriveFocusTimeline(input).segments;
}

export function deriveFocusTimeline({ focusStart, until, schedule, events }: DeriveSegmentsInput): FocusTimeline {
  const sorted = events.filter((e) => e.at >= focusStart && e.at <= until).sort((a, b) => a.at - b.at);
  const segments: Segment[] = [];
  const push = (kind: SegmentKind, start: Instant, end: Instant, auto?: boolean): void => {
    if (end > start) segments.push(auto ? { kind, start, end, auto } : { kind, start, end });
  };

  let state: SegmentKind = "focus";
  let segStart = focusStart;
  let resumeAt = focusStart;
  let breakCount = 0;
  let breakEndAt: Instant | null = null;
  let breakIsAuto = false;
  let i = 0;

  while (segStart < until) {
    const next = sorted[i];
    if (state === "focus") {
      const autoAt = schedule.mode === "auto" ? resumeAt + schedule.focusMinutes * MINUTE : Number.POSITIVE_INFINITY;
      if (next && next.at <= Math.min(autoAt, until)) {
        i++;
        if (next.type === "break_start") {
          push("focus", segStart, next.at);
          breakCount++;
          state = "break";
          breakIsAuto = false;
          breakEndAt = null;
          segStart = next.at;
        }
        continue;
      }
      if (autoAt < until) {
        push("focus", segStart, autoAt);
        breakCount++;
        state = "break";
        breakIsAuto = true;
        breakEndAt = autoAt + breakLengthMs(schedule, breakCount);
        segStart = autoAt;
        continue;
      }
      push("focus", segStart, until);
      break;
    }

    if (state === "break") {
      const endAt = breakEndAt ?? Number.POSITIVE_INFINITY;
      if (next && next.at <= Math.min(endAt, until)) {
        i++;
        if (next.type === "break_end" || next.type === "back") {
          push("break", segStart, next.at, breakIsAuto);
          state = "focus";
          resumeAt = next.at;
          segStart = next.at;
        }
        continue;
      }
      if (endAt < until) {
        push("break", segStart, endAt, breakIsAuto);
        state = "awaiting_return";
        segStart = endAt;
        continue;
      }
      push("break", segStart, until, breakIsAuto);
      break;
    }

    // awaiting_return
    if (next && next.at <= until) {
      i++;
      if (next.type === "back" || next.type === "break_end") {
        push("awaiting_return", segStart, next.at);
        state = "focus";
        resumeAt = next.at;
        segStart = next.at;
      } else if (next.type === "break_start") {
        push("awaiting_return", segStart, next.at);
        breakCount++;
        state = "break";
        breakIsAuto = false;
        breakEndAt = null;
        segStart = next.at;
      }
      continue;
    }
    push("awaiting_return", segStart, until);
    break;
  }
  return { segments, current: state };
}

/** When the next automatic break starts, if the user is focusing under an automatic schedule. */
export function nextAutoBreakAt(timeline: FocusTimeline, schedule: BreakSchedule): Instant | null {
  if (timeline.current !== "focus" || schedule.mode !== "auto") return null;
  const last = timeline.segments[timeline.segments.length - 1];
  if (!last) return null;
  // A focus segment that started at the last resume; if the timeline ended on a different kind,
  // focus resumed exactly at `until` and the next break is a full interval away.
  const resumedAt = last.kind === "focus" ? last.start : last.end;
  return resumedAt + schedule.focusMinutes * MINUTE;
}

export function totalMs(segments: readonly Segment[], kind: SegmentKind): number {
  return segments.filter((s) => s.kind === kind).reduce((sum, s) => sum + (s.end - s.start), 0);
}

/**
 * Focus intervals completed before an early exit: those ended by a break. The interval in
 * progress at exit is not credited (FR-014). Example: 5 hourly breaks, exit in the last hour → 4h.
 */
export function completedFocusSegments(segments: readonly Segment[]): Segment[] {
  return segments.filter((s, i) => s.kind === "focus" && segments[i + 1] !== undefined);
}
